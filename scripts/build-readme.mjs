#!/usr/bin/env node
/**
 * Pull the published offers from ashiwanikumar.com's API and regenerate
 * offers.json and README.md. Exits non-zero (leaving both files untouched)
 * if the API can't be reached, so a failed run never wipes the list.
 *
 *   node scripts/build-readme.mjs
 *   VOUCHERS_API=http://localhost:5099/api/v1 node scripts/build-readme.mjs
 */
import { readFile, writeFile } from "node:fs/promises";

const API = (process.env.VOUCHERS_API || "https://api.ashiwanikumar.com/api/v1").replace(/\/$/, "");
const SITE = "https://ashiwanikumar.com/certification-vouchers";

const STATUS_LABEL = { active: "Open", ongoing: "Ongoing", upcoming: "Coming up", closed: "Finished" };

const fmt = (iso) =>
  iso ? new Date(iso).toLocaleDateString("en-GB", { day: "numeric", month: "short", year: "numeric", timeZone: "UTC" }) : "";

function dates(o) {
  if (o.startDate && o.endDate) return `${fmt(o.startDate)} – ${fmt(o.endDate)}`;
  if (o.endDate) return `Until ${fmt(o.endDate)}`;
  if (o.startDate) return `From ${fmt(o.startDate)}`;
  return "No fixed end date";
}

// Keep table cells on one line and stop stray pipes breaking the table.
const cell = (text) => String(text ?? "").replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();

function table(offers) {
  const rows = offers.map(
    (o) =>
      `| [${cell(o.title)}](${SITE}/${o.slug}) | ${cell((o.exams || []).join(", "))} | **${cell(o.discount)}** | ${cell(dates(o))} | ${STATUS_LABEL[o.status] || o.status} |`
  );
  return ["| Offer | Exams | Discount | When | Status |", "|---|---|---|---|---|", ...rows].join("\n");
}

function details(o) {
  const lines = [`### ${o.title}`, "", `${STATUS_LABEL[o.status] || o.status} · ${o.provider} · **${o.discount}**`, ""];
  if (o.summary) lines.push(o.summary, "");
  if (o.exams?.length) lines.push(`- **Exams:** ${o.exams.join(", ")}`);
  lines.push(`- **Dates:** ${dates(o)}`);
  if (o.eligibility) lines.push(`- **Who can get it:** ${o.eligibility}`);
  if (o.validity && o.status !== "closed") lines.push(`- **How long the voucher lasts:** ${o.validity}`);
  lines.push("");
  if (o.steps?.length) {
    lines.push("How to get it:", "", ...o.steps.map((s, i) => `${i + 1}. ${s}`), "");
  }
  const links = [`[More on my site](${SITE}/${o.slug})`, ...(o.links || []).map((l) => `[${l.label}](${l.url})`)];
  lines.push(links.join(" · "), "");
  return lines.join("\n");
}

function readme(offers, updatedAt) {
  const open = offers.filter((o) => o.status !== "closed");
  const past = offers.filter((o) => o.status === "closed");

  return `<!-- Generated by scripts/build-readme.mjs from the site's API. Edits here get overwritten. -->

# Microsoft & Azure certification vouchers

Microsoft exams aren't cheap, but every so often there's a way to take one for free or at half price. This is my running list of those offers: AZ-900, AZ-104, AI-900, PL-300, the Fabric exams, whatever turns up.

The same list is on my site at [ashiwanikumar.com/certification-vouchers](${SITE}). You can leave your email there and I'll let you know when a new one opens.

Last updated ${fmt(updatedAt) || fmt(new Date().toISOString())}.

## Open right now

${open.length ? table(open) : "Nothing running at the moment. [Leave your email](" + SITE + "#enroll) and I'll tell you when the next one starts."}

## Already finished

These are over, but most of them come back in some form, so they're a decent guide to what to watch for.

${past.length ? table(past) : "None yet."}

## Details

${open.map(details).join("\n")}
${past.length ? "<details>\n<summary>Finished offers</summary>\n\n" + past.map(details).join("\n") + "\n</details>\n" : ""}
## Spotted one I've missed?

[Open an issue](../../issues/new?template=new-offer.yml) with a link to the official announcement and I'll add it. A link to the actual Microsoft page helps a lot more than a YouTube video or a repost.

## Using the data

[\`offers.json\`](offers.json) has everything that's in this README. If you'd rather call the API directly: \`GET ${API}/cert-vouchers/offers\`.

## Disclaimer

I'm not connected to Microsoft, DataCamp or GitHub, I just keep this list. Offers change or get pulled without warning, so check the official page before you pay for anything.

[Ashiwani Kumar](https://ashiwanikumar.com)
`;
}

// VOUCHERS_FILE=path.json builds from a local file instead (handy before the API is up).
let data;
if (process.env.VOUCHERS_FILE) {
  data = JSON.parse(await readFile(process.env.VOUCHERS_FILE, "utf8"));
} else {
  const response = await fetch(`${API}/cert-vouchers/offers`, { headers: { Accept: "application/json" } });
  if (!response.ok) {
    console.error(`API returned ${response.status}; leaving files unchanged.`);
    process.exit(1);
  }
  data = await response.json();
}
const { offers, updatedAt } = data;
if (!Array.isArray(offers)) {
  console.error("API response has no offers array; leaving files unchanged.");
  process.exit(1);
}

await writeFile("offers.json", JSON.stringify({ updatedAt, offers }, null, 2) + "\n");
await writeFile("README.md", readme(offers, updatedAt));
console.log(`Wrote ${offers.length} offers.`);
